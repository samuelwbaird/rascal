-- Generate modules.c: the compiled in C modules, embedded Lua sources and
-- dependency versions, from the modules.list file written by the Makefile.
--
--   lua tools/embed.lua <modules.list> <modules.c>
--
-- modules.list has one entry per line:
--   version <rascal version>
--   platform <platform>
--   srcroot <directory dependency sources are unpacked in>
--   dep <name> <version>
--   cmodule <module name> <luaopen function>
--   lua <module name> <source file>

local list_path, output_path = ...
assert(list_path and output_path, 'usage: embed.lua <modules.list> <modules.c>')

local version, platform, srcroot = '', '', nil
local deps, cmodules, luamodules = {}, {}, {}
local seen = {}

local function read_file(path)
	local f = assert(io.open(path, 'rb'))
	local content = f:read('a')
	f:close()
	return content
end

for line in io.lines(list_path) do
	local kind, a, b = line:match('^(%S+)%s*(%S*)%s*(%S*)$')
	if kind == 'version' then
		version = a
	elseif kind == 'platform' then
		platform = a
	elseif kind == 'srcroot' then
		srcroot = a
	elseif kind == 'dep' then
		deps[#deps + 1] = { name = a, version = b }
	elseif kind == 'cmodule' or kind == 'lua' then
		if seen[a] then
			error('module ' .. a .. ' is provided twice (' .. seen[a] .. ' and ' .. kind .. ')')
		end
		seen[a] = kind
		if kind == 'cmodule' then
			cmodules[#cmodules + 1] = { name = a, open = b }
		else
			luamodules[#luamodules + 1] = { name = a, path = b }
		end
	elseif kind then
		error('unknown entry in ' .. list_path .. ': ' .. line)
	end
end

table.sort(cmodules, function (x, y) return x.name < y.name end)
table.sort(luamodules, function (x, y) return x.name < y.name end)

local out = {}
local function emit(...)
	for i = 1, select('#', ...) do
		out[#out + 1] = select(i, ...)
	end
end

local function c_string(s)
	local escaped = s:gsub('[\\"]', '\\%0'):gsub('[^%w%p ]', function (c)
		return string.format('\\%03o', c:byte())
	end)
	return '"' .. escaped .. '"'
end

-- sources are emitted as byte arrays, which avoids any limits on the length
-- of string literals and any question of escaping
local function c_bytes(s)
	local lines, line = {}, {}
	for i = 1, #s do
		line[#line + 1] = tostring(s:byte(i))
		if #line == 24 then
			lines[#lines + 1] = table.concat(line, ',')
			line = {}
		end
	end
	line[#line + 1] = '0'
	lines[#lines + 1] = table.concat(line, ',')
	return table.concat(lines, ',\n')
end

-- show dependency sources relative to the unpacked sources, not the build dir
local function display_path(path)
	if srcroot and path:sub(1, #srcroot + 1) == srcroot .. '/' then
		return path:sub(#srcroot + 2)
	end
	return path
end

emit('/* generated by tools/embed.lua, do not edit */\n\n')
emit('#include "rascal.h"\n\n')

emit('const char rascal_version[] = ', c_string(version), ';\n')
emit('const char rascal_platform[] = ', c_string(platform), ';\n\n')

for _, m in ipairs(cmodules) do
	emit('int ', m.open, ' (lua_State *L);\n')
end
emit('\nconst rascal_CModule rascal_cmodules[] = {\n')
for _, m in ipairs(cmodules) do
	emit('  { ', c_string(m.name), ', ', m.open, ' },\n')
end
emit('  { 0, 0 }\n};\n\n')

for i, m in ipairs(luamodules) do
	m.source = read_file(m.path)
	emit('/* ', m.name, ' */\n')
	emit('static const char lua_source_', i, '[] = {\n', c_bytes(m.source), '\n};\n\n')
end
emit('const rascal_LuaModule rascal_luamodules[] = {\n')
for i, m in ipairs(luamodules) do
	emit('  { ', c_string(m.name), ', ', c_string(display_path(m.path)), ', lua_source_', i, ', ', #m.source, ' },\n')
end
emit('  { 0, 0, 0, 0 }\n};\n\n')

emit('const rascal_Dependency rascal_dependencies[] = {\n')
for _, d in ipairs(deps) do
	emit('  { ', c_string(d.name), ', ', c_string(d.version), ' },\n')
end
emit('  { 0, 0 }\n};\n')

local f = assert(io.open(output_path, 'wb'))
f:write(table.concat(out))
f:close()
