#!/bin/sh
# Write the Homebrew formula for a release, using the release's SHA256SUMS.
#
#   scripts/homebrew-formula.sh <version> <SHA256SUMS> > Formula/rascal.rb
#
# The formula installs the prebuilt executable for the platform, from the
# release on GitHub. Used by .github/workflows/release.yml to update the tap
# at https://github.com/samuelwbaird/homebrew-tap

set -eu

version=$1
sums=$2
releases=https://github.com/samuelwbaird/rascal/releases/download/v$version

sha256() {
	file=rascal-$version-$1.tar.gz
	sum=$(grep " $file\$" "$sums" | cut -d' ' -f1)
	if [ -z "$sum" ]; then
		echo "homebrew-formula.sh: $file is not in $sums" >&2
		exit 1
	fi
	echo "$sum"
}

cat <<FORMULA
# generated by scripts/homebrew-formula.sh in https://github.com/samuelwbaird/rascal
class Rascal < Formula
  desc "Single executable Lua with SQLite, ZeroMQ, threads and HTTP built in"
  homepage "https://github.com/samuelwbaird/rascal"

  on_macos do
    on_arm do
      url "$releases/rascal-$version-darwin-arm64.tar.gz"
      sha256 "$(sha256 darwin-arm64)"
    end
    on_intel do
      url "$releases/rascal-$version-darwin-x86_64.tar.gz"
      sha256 "$(sha256 darwin-x86_64)"
    end
  end

  on_linux do
    on_arm do
      url "$releases/rascal-$version-linux-aarch64-static.tar.gz"
      sha256 "$(sha256 linux-aarch64-static)"
    end
    on_intel do
      url "$releases/rascal-$version-linux-x86_64-static.tar.gz"
      sha256 "$(sha256 linux-x86_64-static)"
    end
  end

  def install
    bin.install "rascal"
    doc.install "LICENSES.txt"
  end

  test do
    output = shell_output("#{bin}/rascal -e \"print(require('rascal.build').version)\"")
    assert_equal version.to_s, output.strip
  end
end
FORMULA
